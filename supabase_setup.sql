-- Карта ЛПУ 2.0: профілі користувачів та спільні додані спеціальності
-- Увімкніть Anonymous Sign-Ins у Supabase Dashboard > Authentication > Sign In / Providers.

CREATE TABLE IF NOT EXISTS public.lpu_user_profiles (
  user_id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  surname TEXT NOT NULL CHECK (char_length(surname) BETWEEN 2 AND 80),
  is_admin BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.clinic_extra_specialties (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clinic_name TEXT NOT NULL,
  specialty TEXT NOT NULL,
  added_by_surname TEXT NOT NULL,
  user_id UUID NOT NULL REFERENCES auth.users(id),
  is_admin BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (clinic_name, specialty)
);

ALTER TABLE public.clinic_extra_specialties ADD COLUMN IF NOT EXISTS added_by_surname TEXT;
ALTER TABLE public.clinic_extra_specialties ADD COLUMN IF NOT EXISTS user_id UUID REFERENCES auth.users(id);
ALTER TABLE public.clinic_extra_specialties ADD COLUMN IF NOT EXISTS is_admin BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE public.lpu_user_profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.clinic_extra_specialties ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public can read specialties" ON public.clinic_extra_specialties;
DROP POLICY IF EXISTS "Public can add specialties" ON public.clinic_extra_specialties;
DROP POLICY IF EXISTS "Authenticated can read specialties" ON public.clinic_extra_specialties;
DROP POLICY IF EXISTS "Users can add attributed specialties" ON public.clinic_extra_specialties;
DROP POLICY IF EXISTS "Admins can delete specialties" ON public.clinic_extra_specialties;
DROP POLICY IF EXISTS "Users can read own profile" ON public.lpu_user_profiles;
DROP POLICY IF EXISTS "Users can create own profile" ON public.lpu_user_profiles;

CREATE POLICY "Users can read own profile" ON public.lpu_user_profiles
  FOR SELECT TO authenticated USING (user_id = auth.uid());
CREATE POLICY "Users can create own profile" ON public.lpu_user_profiles
  FOR INSERT TO authenticated WITH CHECK (user_id = auth.uid() AND is_admin = FALSE);

CREATE POLICY "Authenticated can read specialties" ON public.clinic_extra_specialties
  FOR SELECT TO authenticated USING (TRUE);
CREATE POLICY "Users can add attributed specialties" ON public.clinic_extra_specialties
  FOR INSERT TO authenticated WITH CHECK (
    user_id = auth.uid()
    AND EXISTS (
      SELECT 1 FROM public.lpu_user_profiles p
      WHERE p.user_id = auth.uid()
        AND p.surname = added_by_surname
        AND p.is_admin = is_admin
    )
  );
CREATE POLICY "Admins can delete specialties" ON public.clinic_extra_specialties
  FOR DELETE TO authenticated USING (
    EXISTS (SELECT 1 FROM public.lpu_user_profiles p WHERE p.user_id = auth.uid() AND p.is_admin = TRUE)
  );

GRANT SELECT, INSERT ON public.lpu_user_profiles TO authenticated;
GRANT SELECT, INSERT, DELETE ON public.clinic_extra_specialties TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.clinic_extra_specialties_id_seq TO authenticated;
