CREATE OR REPLACE FUNCTION public.is_lpu_admin()
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.lpu_user_profiles
    WHERE user_id=auth.uid() AND is_admin=TRUE
  );
$$;

CREATE TABLE IF NOT EXISTS public.rare_service_records (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  category text NOT NULL,
  name text NOT NULL,
  city text NOT NULL DEFAULT '',
  area text NOT NULL DEFAULT '',
  clinic text NOT NULL DEFAULT '',
  address text NOT NULL DEFAULT '',
  availability text NOT NULL DEFAULT '',
  price text NOT NULL DEFAULT '',
  conditions text NOT NULL DEFAULT '',
  notes text NOT NULL DEFAULT '',
  source_sheet text NOT NULL DEFAULT '',
  source_row integer,
  raw_data jsonb NOT NULL DEFAULT '{}'::jsonb,
  status text NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','approved','rejected')),
  submitted_by_surname text NOT NULL DEFAULT '',
  user_id uuid REFERENCES auth.users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  reviewed_by text,
  reviewed_at timestamptz
);

CREATE INDEX IF NOT EXISTS rare_service_records_status_idx ON public.rare_service_records(status);
CREATE INDEX IF NOT EXISTS rare_service_records_city_idx ON public.rare_service_records(city);
CREATE INDEX IF NOT EXISTS rare_service_records_category_idx ON public.rare_service_records(category);
CREATE INDEX IF NOT EXISTS rare_service_records_name_idx ON public.rare_service_records(name);

ALTER TABLE public.rare_service_records ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public read approved rare services" ON public.rare_service_records;
CREATE POLICY "Public read approved rare services"
ON public.rare_service_records FOR SELECT TO anon, authenticated
USING (status='approved' OR public.is_lpu_admin() OR user_id=auth.uid());

DROP POLICY IF EXISTS "Signed in users submit rare service suggestions" ON public.rare_service_records;
CREATE POLICY "Signed in users submit rare service suggestions"
ON public.rare_service_records FOR INSERT TO authenticated
WITH CHECK (
  status='pending'
  AND user_id=auth.uid()
  AND EXISTS (
    SELECT 1 FROM public.lpu_user_profiles p
    WHERE p.user_id=auth.uid() AND p.surname=submitted_by_surname
  )
);

DROP POLICY IF EXISTS "Admins manage rare service records" ON public.rare_service_records;
CREATE POLICY "Admins manage rare service records"
ON public.rare_service_records FOR ALL TO authenticated
USING (public.is_lpu_admin())
WITH CHECK (public.is_lpu_admin());

GRANT SELECT ON public.rare_service_records TO anon, authenticated;
GRANT INSERT ON public.rare_service_records TO authenticated;
GRANT UPDATE, DELETE ON public.rare_service_records TO authenticated;

-- Reuse the common admin-only change archive used by the main site.
CREATE TABLE IF NOT EXISTS public.lpu_change_archive (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_table text NOT NULL,
  entity_id text,
  action text NOT NULL CHECK(action IN ('INSERT','UPDATE','DELETE')),
  actor_user_id uuid,
  actor_surname text,
  old_data jsonb,
  new_data jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.lpu_change_archive ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Only admins read change archive" ON public.lpu_change_archive;
CREATE POLICY "Only admins read change archive"
ON public.lpu_change_archive FOR SELECT TO authenticated
USING(public.is_lpu_admin());
GRANT SELECT ON public.lpu_change_archive TO authenticated;

CREATE OR REPLACE FUNCTION public.log_rare_service_change()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE
  oldj jsonb; newj jsonb; rowj jsonb; actor text;
BEGIN
  IF TG_OP='INSERT' THEN newj=to_jsonb(NEW); rowj=newj;
  ELSIF TG_OP='UPDATE' THEN oldj=to_jsonb(OLD); newj=to_jsonb(NEW); rowj=newj;
  ELSE oldj=to_jsonb(OLD); rowj=oldj;
  END IF;

  SELECT surname INTO actor FROM public.lpu_user_profiles
  WHERE user_id=auth.uid() LIMIT 1;

  INSERT INTO public.lpu_change_archive(entity_table,entity_id,action,actor_user_id,actor_surname,old_data,new_data)
  VALUES('rare_service_records',rowj->>'id',TG_OP,auth.uid(),COALESCE(actor,'Імпорт / системна дія'),oldj,newj);

  IF TG_OP='DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS audit_rare_service_records ON public.rare_service_records;
CREATE TRIGGER audit_rare_service_records
AFTER INSERT OR UPDATE OR DELETE ON public.rare_service_records
FOR EACH ROW EXECUTE FUNCTION public.log_rare_service_change();
